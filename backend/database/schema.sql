-- ==========================================
-- 1. TABLAS PADRE 
-- ==========================================

CREATE TABLE departamento (
    ID_DEP VARCHAR2(5) PRIMARY KEY,
    NOM_DEP VARCHAR2(100) NOT NULL,
    NUM_EMPLEADOS NUMBER NOT NULL
);

-- ==========================================
-- 2. USUARIOS 
-- ==========================================

CREATE TABLE Empleado (
    NUM_TEL VARCHAR2(10) PRIMARY KEY,
    NOMBRE VARCHAR2(50) NOT NULL,
    APELLIDO_PAT VARCHAR2(50) NOT NULL,
    APELLIDO_MAT VARCHAR2(50),
    CORREO VARCHAR2(100) NOT NULL,
    PUESTO VARCHAR2(50) NOT NULL,
    FOTO_PERFIL BLOB,
    ID_DEP VARCHAR2(5) NOT NULL,
    CONTRASENA VARCHAR2(100) NOT NULL,
    ID_EMPLEADO_INTERNO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT fk_emp_dep FOREIGN KEY (ID_DEP) REFERENCES departamento(ID_DEP)
);

-- ==========================================
-- 3. GESTIÓN DE CHATS Y CONTACTOS 
-- ==========================================

CREATE TABLE contactos (
    ID_CONTACTO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USUARIO_DUENO VARCHAR2(10) NOT NULL,
    USUARIO_AGREGADO VARCHAR2(10) NOT NULL,
    CONSTRAINT fk_cont_dueno FOREIGN KEY (USUARIO_DUENO) REFERENCES Empleado(NUM_TEL),
    CONSTRAINT fk_cont_agregado FOREIGN KEY (USUARIO_AGREGADO) REFERENCES Empleado(NUM_TEL)
);

CREATE TABLE chat_individual (
    ID_CHATIND NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FECHA_CREACION DATE DEFAULT SYSDATE,
    USUARIO_1 VARCHAR2(10) NOT NULL,
    USUARIO_2 VARCHAR2(10) NOT NULL,
    CONSTRAINT fk_chatind_u1 FOREIGN KEY (USUARIO_1) REFERENCES Empleado(NUM_TEL),
    CONSTRAINT fk_chatind_u2 FOREIGN KEY (USUARIO_2) REFERENCES Empleado(NUM_TEL)
);

CREATE TABLE chat_grupal (
    ID_CHATGPAL NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE_GRUPO VARCHAR2(100) NOT NULL,
    ADMIN_TEL VARCHAR2(10) NOT NULL,
    FOTO_GRUPO BLOB,
    FECHA_CREACION DATE DEFAULT SYSDATE,
    CONSTRAINT fk_chatgpal_admin FOREIGN KEY (ADMIN_TEL) REFERENCES Empleado(NUM_TEL)
);

CREATE TABLE miembros_grupo (
    ID_MIEMBRO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CHATGPAL NUMBER NOT NULL,
    NUM_TEL VARCHAR2(10) NOT NULL,
    FECHA_UNIDO DATE DEFAULT SYSDATE,
    CONSTRAINT fk_miembros_chat FOREIGN KEY (ID_CHATGPAL) REFERENCES chat_grupal(ID_CHATGPAL) ON DELETE CASCADE,
    CONSTRAINT fk_miembros_emp FOREIGN KEY (NUM_TEL) REFERENCES Empleado(NUM_TEL)
);

-- ==========================================
-- 4. MENSAJES
-- ==========================================

CREATE TABLE mensajes_ind (
    ID_MSGIND NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CHATIND NUMBER NOT NULL,
    EMISOR VARCHAR2(10) NOT NULL,
    CONTENIDO CLOB,
    ARCHIVO BLOB,
    TIPO_ARCHIVO VARCHAR2(50),
    FECHA_ENVIO TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    HORA_ENVIO VARCHAR2(10),
    ESTADO VARCHAR2(20) DEFAULT 'enviado',
    CONSTRAINT fk_msgind_chat FOREIGN KEY (ID_CHATIND) REFERENCES chat_individual(ID_CHATIND) ON DELETE CASCADE,
    CONSTRAINT fk_msgind_emisor FOREIGN KEY (EMISOR) REFERENCES Empleado(NUM_TEL)
);

CREATE TABLE mensajes_gpal (
    ID_MSGGPAL NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CHATGPAL NUMBER NOT NULL,
    EMISOR VARCHAR2(10) NOT NULL,
    CONTENIDO CLOB,
    ARCHIVO BLOB,
    TIPO_ARCHIVO VARCHAR2(50),
    FECHA_ENVIO TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    HORA_ENVIO VARCHAR2(10),
    ESTADO VARCHAR2(20) DEFAULT 'enviado',
    CONSTRAINT fk_msggpal_chat FOREIGN KEY (ID_CHATGPAL) REFERENCES chat_grupal(ID_CHATGPAL) ON DELETE CASCADE,
    CONSTRAINT fk_msggpal_emisor FOREIGN KEY (EMISOR) REFERENCES Empleado(NUM_TEL)
);

-- ==========================================
-- 5. TRADUCCIONES
-- ==========================================

CREATE TABLE traduccion_ind (
    ID_TRADIND NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_MSGIND NUMBER NOT NULL,
    IDIOMA_ORIGEN VARCHAR2(20),
    IDIOMA_FINAL VARCHAR2(20),
    TEXTO_TRADUCIDO CLOB,
    CONSTRAINT fk_tradind_msg FOREIGN KEY (ID_MSGIND) REFERENCES mensajes_ind(ID_MSGIND) ON DELETE CASCADE
);

CREATE TABLE traduccion_gpal (
    ID_TRADGPAL NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_MSGGPAL NUMBER NOT NULL,
    IDIOMA_ORIGEN VARCHAR2(20),
    IDIOMA_FINAL VARCHAR2(20),
    TEXTO_TRADUCIDO CLOB,
    CONSTRAINT fk_tradgpal_msg FOREIGN KEY (ID_MSGGPAL) REFERENCES mensajes_gpal(ID_MSGGPAL) ON DELETE CASCADE
);